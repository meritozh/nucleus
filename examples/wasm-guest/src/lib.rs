//! Example / test-fixture nucleus Wasm guest.
//!
//! This demonstrates **materialization**: the *same* plugin source code
//! (`MyPlugin` implementing [`nucleus_core::Plugin`]) is compiled as a Wasm
//! component by calling [`nucleus_guest::export_plugin!`]. The identical
//! `MyPlugin` type could also be registered in a `StaticSource` for native
//! deployment — no code changes required.
//!
//! Build (see the repo README "Guest build" for the full path):
//!
//! ```text
//! rustup target add wasm32-unknown-unknown
//! cargo build --release --target wasm32-unknown-unknown
//! wasm-tools component new target/wasm32-unknown-unknown/release/nucleus_guest_example.wasm \
//!     -o nucleus-wasm/tests/fixtures/hello.wasm
//! ```

// Generate the WIT bindings (Guest trait, export! macro, host imports).
wit_bindgen::generate!({
    path: "../../wit",
    world: "plugin",
    generate_all,
});

use async_trait::async_trait;
use nucleus_core::{Context, Plugin};
use nucleus_guest::export_plugin;
use serde_json::Value;
use std::sync::Arc;

/// The plugin. Implements [`Plugin`] exactly as a native (static) plugin
/// would; `export_plugin!` below bridges it to the WIT `plugin` world.
#[derive(Default)]
struct MyPlugin;

#[async_trait]
impl Plugin for MyPlugin {
    fn name(&self) -> &str {
        "hello"
    }

    async fn apply(&self, ctx: Context) -> nucleus_core::Result<()> {
        // Register a reversible effect (host calls dispose-effect at unload).
        // The disposer closure runs when the fiber unloads.
        ctx.effect_fn(|| async {
            // Cleanup logic goes here. The host's dispose-effect export
            // (generated by export_plugin!) emits a "dispose effect=..."
            // marker so the host can observe the unwind.
        });
        ctx.emit_dynamic(
            "guest/log",
            serde_json::json!({"level": "info", "msg": "init effect=registered"}),
        )?;

        // Call a host-provided Invokable service through the Wasm boundary.
        let calc: Arc<dyn nucleus_core::Invokable> = ctx.service("calc")?;
        match calc.invoke("add", serde_json::json!([1, 2])).await {
            Ok(v) => ctx.emit_dynamic(
                "guest/log",
                serde_json::json!({"level": "info", "msg": format!("calc={v}")}),
            )?,
            Err(e) => ctx.emit_dynamic(
                "guest/log",
                serde_json::json!({"level": "error", "msg": format!("calc failed: {e}")}),
            )?,
        }

        // Provide a guest-side Invokable service back to the host.
        ctx.provide::<dyn nucleus_core::Invokable>("guest-echo", Arc::new(GuestEcho))
            .await?;

        Ok(())
    }
}

/// Guest-provided service: echoes back the argument.
struct GuestEcho;

#[async_trait]
impl nucleus_core::Invokable for GuestEcho {
    fn invoke(
        &self,
        method: &str,
        arg: Value,
    ) -> futures::future::BoxFuture<'static, Result<Value, String>> {
        let method = method.to_string();
        Box::pin(async move {
            match method.as_str() {
                "echo" => Ok(arg),
                other => Err(format!("unknown method `{other}`")),
            }
        })
    }
}

// Generate the WIT exports (init, dispose-effect, handle-service) that
// forward to the `Plugin` impl above.
export_plugin!(MyPlugin);
